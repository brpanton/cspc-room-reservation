function buildBlock() {
  const L = [];
  L.push("router.post('/forgot-password', async (req, res, next) => {");
  L.push('  try {');
  L.push('    // DIRECT-DELIVERY MODE (per user request): the visitor types the CSPC');
  L.push('    // email that should RECEIVE the OTP (a School ID is still accepted and');
  L.push('    // resolves to the registered primary email). The typed/delivered address');
  L.push('    // is ONLY a mailing destination: nothing here ever writes to');
  L.push('    // users.email / users.school_id, so the login identity stays safe.');
  L.push('    const rawIdentifier = req.body.identifier !== undefined ? req.body.identifier : req.body.email;');
  L.push("    requireFields({ identifier: rawIdentifier }, ['identifier']);");
  L.push("    const looksLikeEmail = String(rawIdentifier).includes('@');");
  L.push('    let deliveryEmail;');
  L.push('    let rowEmail;');
  L.push('    let user = null;');
  L.push("    let displayName = '';");
  L.push('    if (looksLikeEmail) {');
  L.push('      deliveryEmail = parseEmail(rawIdentifier);');
  L.push('      if (!isCspcEmail(deliveryEmail)) {');
  L.push("        const err = new Error('Enter your @cspc.edu.ph or @my.cspc.edu.ph email address.');");
  L.push('        err.status = 400;');
  L.push('        throw err;');
  L.push('      }');
  L.push('      // Optional link to an existing account (same address) so steps 2-3 can');
  L.push('      // update the password afterwards. Unknown addresses still receive a');
  L.push('      // code - they just cannot complete a password change.');
  L.push('      const [users] = await pool.query(');
  L.push("        'SELECT id, email, first_name, last_name, is_active FROM users WHERE LOWER(email) = LOWER(?) LIMIT 1',");
  L.push('        [deliveryEmail]');
  L.push('      );');
  L.push('      user = users[0] || null;');
  L.push('      rowEmail = deliveryEmail;');
  L.push("      displayName = user ? [user.first_name, user.last_name].filter(Boolean).join(' ') : '';");
  L.push('    } else {');
  L.push('      // School ID: resolve to the registered primary email, which becomes');
  L.push('      // both the OTP row key and the mailbox (recovery address preferred).');
  L.push('      const resolved = await resolveAccountEmail(rawIdentifier);');
  L.push('      if (!resolved.user) {');
  L.push("        const err = new Error('No account was found for that School ID. Try your @cspc.edu.ph / @my.cspc.edu.ph email instead.');");
  L.push('        err.status = 404;');
  L.push('        throw err;');
  L.push('      }');
  L.push('      user = resolved.user;');
  L.push('      rowEmail = resolved.email;');
  L.push('      deliveryEmail = resolved.recoveryEmail || resolved.email;');
  L.push("      displayName = user.full_name || '';");
  L.push('    }');
  L.push('');
  L.push('    if (user && !user.is_active) {');
  L.push("      const err = new Error('This account can no longer recover its password. Please contact the administrator.');");
  L.push('      err.status = 403;');
  L.push('      throw err;');
  L.push('    }');
  L.push('');
  return L.join('\n');
}
module.exports = { buildBlock };
