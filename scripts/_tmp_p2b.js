function buildRest() {
  const L = [];
  L.push('    // Cooldown: one live code per address every RESEND_COOLDOWN_SECONDS.');
  L.push('    const [[last]] = await pool.query(');
  L.push('      `SELECT TIMESTAMPDIFF(SECOND, created_at, NOW()) AS age_seconds');
  L.push('         FROM password_reset_codes');
  L.push('        WHERE email = ?');
  L.push('        ORDER BY id DESC');
  L.push('        LIMIT 1`,');
  L.push('      [rowEmail]');
  L.push('    );');
  L.push('    if (last && Number(last.age_seconds) < RESEND_COOLDOWN_SECONDS) {');
  L.push('      const wait = RESEND_COOLDOWN_SECONDS - Number(last.age_seconds);');
  L.push("      const err = new Error(`Please wait ${wait} second${wait === 1 ? '' : 's'} before requesting another code.`);");
  L.push('      err.status = 429;');
  L.push('      throw err;');
  L.push('    }');
  L.push('');
  L.push('    // Create the code: only the bcrypt hash is stored, never the OTP itself.');
  L.push('    // The row is keyed by the delivery address so verify/reset match exactly');
  L.push('    // what the visitor typed. user_id is NULL for unknown addresses (their');
  L.push('    // verify step passes but reset is refused with "no account" guidance).');
  L.push('    const otp = generateOtp();');
  L.push('    const otpHash = await bcrypt.hash(otp, 10);');
  L.push('');
  L.push('    // Drop anything older for this address so only the newest code is live');
  L.push('    // (this also sweeps up used/expired rows as a cheap cleanup).');
  L.push("    await pool.query('DELETE FROM password_reset_codes WHERE email = ?', [rowEmail]);");
  L.push('    await pool.query(');
  L.push('      `INSERT INTO password_reset_codes (user_id, email, otp_hash, attempts, expires_at)');
  L.push('       VALUES (?, ?, ?, 0, DATE_ADD(NOW(), INTERVAL ${OTP_TTL_MINUTES} MINUTE))`,');
  L.push('      [user ? user.id : null, rowEmail, otpHash]');
  L.push('    );');
  L.push('');
  L.push('    console.log(');
  L.push("      `[password-reset] OTP generated for ${rowEmail}` +");
  L.push("        (user ? ` (user_id=${user.id})` : ' (no matching account - direct delivery only)') +");
  L.push("        ` - delivering to ${deliveryEmail} - handing to mailer...`");
  L.push('    );');
  L.push('    const delivery = await sendPasswordResetOtp({');
  L.push('      email: deliveryEmail,');
  L.push('      name: displayName,');
  L.push('      otp,');
  L.push('      minutes: OTP_TTL_MINUTES');
  L.push('    });');
  L.push("    console.log(`[password-reset] Mailer result for ${deliveryEmail}: ${delivery.delivered ? 'sent' : delivery.reason}`);");
  L.push("    if (delivery.reason === 'error') {");
  L.push('      // sendMail() itself failed (bad credentials, SMTP down, ...): the');
  L.push('      // details are already in the terminal console - tell the frontend');
  L.push('      // with a 5xx instead of pretending the code went out.');
  L.push("      const err = new Error('We could not send the verification email right now. Please try again in a moment.');");
  L.push('      err.status = 500;');
  L.push('      throw err;');
  L.push('    }');
  L.push('    // delivery.reason === unconfigured means SMTP is not set up yet: the');
  L.push('    // OTP was printed to the server console instead, so the flow still');
  L.push('    // works locally while the email integration is being configured.');
  L.push('    res.json({');
  L.push('      message: `A 6-digit verification code has been sent to ${deliveryEmail}. Check your inbox (and spam folder).`,');
  L.push('      expires_in_minutes: OTP_TTL_MINUTES,');
  L.push("      email_delivery: delivery.delivered ? 'smtp' : 'console'");
  L.push('    });');
  L.push('  } catch (err) {');
  L.push('    next(err);');
  L.push('  }');
  L.push('});');
  L.push('');
  L.push('');
  return L.join('\n');
}
module.exports = { buildRest };
